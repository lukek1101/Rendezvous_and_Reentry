function results=finalize_evaluation()
% Read-only reanalysis of saved trajectories; no new designs or propagations.
folder=fileparts(mfilename('fullpath')); saved=load(fullfile(folder,'evaluation.mat'));
results=saved.results;
for k=1:numel(results.robustness)
    row=results.robustness(k);
    if ~row.accepted && row.execution_status=="EXECUTED" && contains(row.opportunity_statuses,"PREDICTED_CAPABILITY_LIMIT")
        results.robustness(k).classification="CORRECTION_CAPABILITY_REJECTED_WITH_OBSERVED_MISS";
    end
end
results.assumptions=struct('navigation',"PERFECT_INSTANTANEOUS_ONLY_NONZERO_NAVIGATION_ERROR_UNSUPPORTED", ...
    'sampling',"TWO_SELECTED_SEEDS_PER_CELL_NO_CONFIDENCE_INTERVAL_OR_RELIABILITY_ESTIMATE", ...
    'initial_scale',[0 1 3],'position_sigma_base_m',20,'velocity_sigma_base_m_s',.02, ...
    'burn_scale',[0 1 3],'gain_sigma_base',.002,'pointing_sigma_base_rad',.0002, ...
    'entry_density_scales',[.9 1 1.1],'entry_ld_scales',[.9 1 1.1], ...
    'range_basis',"EXPLORATORY_LOCAL_AND_THREEFOLD_STRESS_LEVELS_NOT_CALIBRATED_FLIGHT_UNCERTAINTY", ...
    'standalone_entry_bank_deg',30,'standalone_entry_bank_rate_limit_deg_s',10, ...
    'standalone_entry_response_time_s',2,'standalone_entry_control_activity_deg',0, ...
    'phase1_robustness_end',"HANDOFF_ONLY_NO_DOWNSTREAM_REDESIGN", ...
    'proximity_robustness_start',"SEPARATE_FROZEN_ACQUISITION_STATE_NO_CLOSING_REPLAN");
assert(numel(results.design)==8 && numel(results.robustness)==36 && numel(results.entry)==11);
assert(results.precision.entry_endpoint_difference_m<.1);
assert(all([results.proximity.saturation_s]==0));
results.verification.saved_result_consistency=true;
% Directly measure the public-sequence quantities from the saved nominal control.
reference=load(fullfile(folder,'design_02.mat'),'n'); n=reference.n;
results.public_sequence=struct('axis',n.proximity.approach_mode, ...
    'acquisition_m',n.proximity.config.autonomous.insertion_range_m, ...
    'hold_m',n.proximity.config.autonomous.hold_range_m,'standoff_m',n.proximity.config.S4_R_abs, ...
    'peak_controlled_speed_m_min',60*n.proximity.control.max_speed_m_s, ...
    'flight_reproduction',false);
saved.results=results; save(fullfile(folder,'evaluation.mat'),'-struct','saved');
readable=results; readable.verification.apollo=rmfield(readable.verification.apollo,'nominal');
fid=fopen(fullfile(folder,'results.json'),'w'); fprintf(fid,'%s\n',jsonencode(readable,PrettyPrint=true)); fclose(fid);
writetable(struct2table(results.robustness),fullfile(folder,'robustness.csv'));
fprintf('Saved-result checks passed; measured controlled peak speed %.6g m/min.\n',results.public_sequence.peak_controlled_speed_m_min);
end
