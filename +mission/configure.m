function cfg = configure(sys, overrides)
%CONFIGURE Resolve defaults, optimizer JSON, run overrides, and environment.
% Scenario/physical constants come from sys; run settings cannot overwrite them.
run_cfg = mission.merge_settings(Mission_Run_Config(sys), overrides);
sys = apply_run_config_to_sys(sys, run_cfg);
mission_cfg = mission.load_optimizer_config(sys, run_cfg);
% Optimizer artifacts supply manoeuvre candidates, never physical authority.
sys = apply_run_config_to_sys(sys, run_cfg);
sys = apply_environment_env_overrides(sys, run_cfg);
sys = refresh_derived_sys(sys);
sys_orbit = sys;
print_environment_config(sys);
sys = apply_pre_berthing_drag_scope(sys_orbit, run_cfg);
warn_if_mission_json_environment_mismatch(mission_cfg, sys);

% Default Phase 1 custom-maneuver settings. A JSON config exported by the
% Python optimizer can override these values without editing this script.
custom_params = struct();

% Parameters for CUSTOM_IMPULSE mode. These are normally generated by the
% Python shooting optimizer.
% custom_params.phase_angle = deg2rad(3.8242);        % [rad]
% custom_params.delta_v     = 57.9955;                % [m/s]
% custom_params.gamma       = deg2rad(0.076877);      % [rad]

custom_params.phase_angle = deg2rad(3.5663);        % [rad]
custom_params.delta_v     = 64.2342;                % [m/s]
custom_params.gamma       = deg2rad(-1.416);        % [rad]

custom_params.phase_angle_unit = "rad"; % "rad" or "deg"
custom_params.gamma_unit       = "rad"; % "rad" or "deg"

% Maneuver execution model for the custom phased maneuver.
% Use "IMPULSIVE" for the legacy instantaneous delta-V model or
% "FINITE_BURN" to execute the same delta-V over a finite-duration firing.
% phase_angle, delta_v, and gamma parameters.
custom_params.burn_model = sys.maneuver.default_burn_model;
custom_params.burn_direction_mode = sys.maneuver.direction_mode;
custom_params.finite_burn_thrust = sys.maneuver.finite_burn_thrust; % [N]
custom_params.finite_burn_isp = sys.maneuver.finite_burn_isp;       % [s]
custom_params.dt_burn = sys.maneuver.finite_burn_dt;                % [s]
custom_params.max_single_burn_duration = sys.maneuver.max_single_burn_duration; % [s]
custom_params.max_single_burn_delta_v = sys.maneuver.max_single_burn_delta_v;   % [m/s]
custom_params.use_thrust_noise = get_run_bool_field(run_cfg, {'maneuver','use_thrust_noise'}, false);
custom_params.multi_hohmann_legs = []; % Used only when phasing_mode is explicitly MULTI_HOHMANN.

% Phase 1 target relative position in the target LVLH frame [m].
custom_params.desired_rel_lvlh = [0; -5000; 0];

% Event detection and propagation settings.
custom_params.time_step = 10;           % [s] nominal propagation step
custom_params.dt_phase = 5;             % [s] coarse phase-angle detection step
custom_params.dt_capture = 5;           % [s] coarse capture detection step
custom_params.max_wait = 2*pi * sys.mu^(-0.5) / ((sys.Re + sys.h_insert)^(-1.5) - (sys.Re + sys.h_target)^(-1.5));
custom_params.max_capture_time = 30000; % [s] maximum post-burn capture search time
custom_params.phase_tol = 1e-7;         % [rad] phase-angle event tolerance
custom_params.event_time_tol = 1e-3;    % [s] event refinement tolerance
custom_params.capture_pos_tol = 0.5;    % [m] capture tolerance about desired_rel_lvlh
custom_params.min_capture_time = 0;     % [s] raise to ignore very early local minima

% Mode options: "CUSTOM_IMPULSE", "HOHMANN"; "MULTI_HOHMANN" is preliminary.
phasing_mode = "CUSTOM_IMPULSE";
[phasing_mode, custom_params] = apply_json_to_phase1(phasing_mode, custom_params, mission_cfg);
[phasing_mode, custom_params] = apply_run_config_to_phase1(phasing_mode, custom_params, run_cfg);
[phasing_mode, custom_params] = apply_phase1_env_overrides(phasing_mode, custom_params, run_cfg);
if ~isempty(fieldnames(mission_cfg)) && phasing_mode=="CUSTOM_IMPULSE" && ...
        (~has_json_path(mission_cfg,{'phase1','delta_v_m_s'}) || ...
        ~(has_json_path(mission_cfg,{'phase1','phase_angle_deg'}) || has_json_path(mission_cfg,{'phase1','phase_angle_rad'})) || ...
        ~(has_json_path(mission_cfg,{'phase1','gamma_deg'}) || has_json_path(mission_cfg,{'phase1','gamma_rad'})))
    error('mission:IncompleteManeuverDesign','Optimizer artifact lacks explicit custom manoeuvre parameters.');
end
if isempty(fieldnames(mission_cfg)) && phasing_mode=="CUSTOM_IMPULSE" && ...
        (~has_nonempty_run_value(overrides,{'phase1','delta_v_m_s'}) || ...
        ~(has_nonempty_run_value(overrides,{'phase1','phase_angle_deg'}) || has_nonempty_run_value(overrides,{'phase1','phase_angle_rad'})) || ...
        ~(has_nonempty_run_value(overrides,{'phase1','gamma_deg'}) || has_nonempty_run_value(overrides,{'phase1','gamma_rad'})))
    error('mission:MissingManeuverDesign','CUSTOM_IMPULSE without an archive requires explicit phase angle, delta-V and gamma. Historical fallback numbers are not a new design.');
end


p2 = default_phase2_config();
% Phase 2 settings are local configuration, not Python authority.
p2 = apply_run_config_to_phase2(p2, run_cfg);
p2.mode = upper(string(run_cfg.phase2.mode));
p2.autonomous = run_cfg.phase2.autonomous;
p3 = default_phase3_config();
% Phase 3 settings are local configuration, not Python authority.
p3 = apply_run_config_to_phase3(p3, run_cfg);
p3.apogee_burns = run_cfg.phase3.apogee_burns;
p3 = apply_phase3_env_overrides(p3, run_cfg);
if p3.mode ~= "HOHMANN"
    error('mission:UnsupportedDeorbitMode', 'Phase 3 supports only HOHMANN direct descent.');
end
cfg = struct('system', sys_orbit, 'proximity_system', sys, ...
    'run', run_cfg, 'optimizer', mission_cfg, 'phase1_mode', phasing_mode, ...
    'phase1', custom_params, 'phase2', p2, 'phase3', p3, ...
    'deorbit', apply_phase3_config_to_params(custom_params, p3));
cfg.provenance=struct('reference',sys.reference,'run_overrides',overrides, ...
    'environment_enabled',run_cfg.runtime.allow_environment_overrides);
cfg.contract=mission.physics_contract(sys_orbit,run_cfg);
cfg.deorbit.compatibility=cfg.contract;
mission.validate_optimizer_compatibility(mission_cfg,cfg.contract,run_cfg,sys.reference.preset);
mission.validate_configuration(cfg);
end

function sys = apply_run_config_to_sys(sys, run_cfg)
    sys.reentry_vehicle.aoa_profile=run_cfg.reentry.aoa_profile;
    sys.h_entry_interface = get_run_number_field(run_cfg, {'phase3','entry_interface_altitude_km'}, sys.h_entry_interface/1e3) * 1e3;
    sys.reentry_flight_path_angle = deg2rad(get_run_number_field(run_cfg, {'phase3','flight_path_angle_deg'}, rad2deg(sys.reentry_flight_path_angle)));

    sys.maneuver.default_burn_model = get_run_string_field(run_cfg, {'maneuver','burn_model'}, sys.maneuver.default_burn_model);
    sys.maneuver.finite_burn_thrust = get_run_number_field(run_cfg, {'maneuver','finite_burn_thrust_N'}, sys.maneuver.finite_burn_thrust);
    sys.maneuver.finite_burn_isp = get_run_number_field(run_cfg, {'maneuver','finite_burn_isp_s'}, sys.maneuver.finite_burn_isp);
