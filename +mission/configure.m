function tf = has_nonempty_run_value(s, path)
    tf = has_run_path(s, path) && ~isempty(get_run_value(s, path, []));
end

function value = get_run_number_field(s, path, default_value)
    value = get_run_value(s, path, default_value);
    if ischar(value) || isstring(value)
        value = str2double(value);
    end
    if isempty(value) || ~isnumeric(value) || ~isscalar(value) || isnan(value)
        value = default_value;
    end
end

function vec = get_run_vector_field(s, path, default_value)
    vec = get_run_value(s, path, default_value);
    if isempty(vec)
        vec = default_value;
    end
    vec = vec(:);
    if numel(vec) ~= numel(default_value) || ~isnumeric(vec) || any(~isfinite(vec))
        vec = default_value(:);
    end
end

function sys = apply_environment_env_overrides(sys, run_cfg)
    if nargin < 2
        run_cfg = struct();
    end
    if ~get_run_bool_field(run_cfg, {'runtime','allow_environment_overrides'}, true)
        return;
    end

    drag_model_env = strtrim(string(getenv('RENDEZVOUS_ATMOSPHERIC_DRAG')));
    if strlength(drag_model_env) > 0
        if upper(drag_model_env) == "OFF" || upper(drag_model_env) == "NONE" || upper(drag_model_env) == "0"
            sys.environment.atmospheric_drag.enabled = false;
        else
            sys.environment.atmospheric_drag.enabled = true;
            sys.environment.atmospheric_drag.model = upper(drag_model_env);
        end
    end

    reentry_shape_env = strtrim(string(getenv('RENDEZVOUS_REENTRY_SHAPE')));
    if strlength(reentry_shape_env) > 0
        sys.reentry_vehicle.selected_shape = upper(reentry_shape_env);
    end
end

function print_environment_config(sys)
    fprintf('Scenario (Mission_Config.m): insertion %.1f km, target %.1f km\n', ...
            sys.h_insert/1000, sys.h_target/1000);
    fprintf('Maneuver model: %s, thrust %.1f N, Isp %.1f s\n', ...
            char(string(sys.maneuver.default_burn_model)), sys.maneuver.finite_burn_thrust, sys.maneuver.finite_burn_isp);
    fprintf('Phase 3 geometry: entry interface %.1f km, FPA %.2f deg\n', ...
            sys.h_entry_interface/1000, rad2deg(sys.reentry_flight_path_angle));
    drag = sys.environment.atmospheric_drag;
    if drag.enabled
        fprintf('Environment: orbital atmospheric drag ON (%s), Cd/A chaser %.2f/%.2f m^2, target %.2f/%.2f m^2\n', ...
                char(string(drag.model)), drag.chaser_cd, drag.chaser_area_m2, drag.target_cd, drag.target_area_m2);
    else
        fprintf('Environment: orbital atmospheric drag OFF\n');
    end
    reentry_shape = string(sys.reentry_vehicle.selected_shape);
    if upper(string(sys.reentry_vehicle.vehicle_mode)) == "CAPSULE"
        reentry_shape = "CAPSULE";
    end
    if upper(string(sys.reentry_vehicle.vehicle_mode)) == "CAPSULE" && ...
            ~sys.reentry_vehicle.capsule.altitude_termination_enabled
        fprintf(['Re-entry vehicle: mode %s, shape %s, nominal stop %.1f m/s, ' ...
                 'ground safety %.1f km, lift model %s, entry atmosphere ISA76\n'], ...
                char(string(sys.reentry_vehicle.vehicle_mode)), char(reentry_shape), ...
                sys.reentry_vehicle.capsule.parachute_deploy_speed_m_s, ...
                sys.reentry_vehicle.capsule.safety_floor_altitude_m/1000, ...
                char(bool_label(sys.reentry_vehicle.lift_enabled)));
    else
        fprintf('Re-entry vehicle: mode %s, shape %s, terminal altitude %.1f km, lift model %s, entry atmosphere ISA76\n', ...
                char(string(sys.reentry_vehicle.vehicle_mode)), char(reentry_shape), ...
                sys.reentry_vehicle.terminal_altitude/1000, ...
                char(bool_label(sys.reentry_vehicle.lift_enabled)));
    end
    communication = sys.reentry_vehicle.spaceplane.communication;
    if upper(string(communication.relay_mode)) == ...
            "PAPER_TDRS_STATIC_EARTH_FIXED"
        fprintf(['Paper TDRS ECEF->ECI convention: Greenwich angle at ' ...
                 'mission epoch %.6f deg\n'], ...
            communication.earth_fixed_to_eci_angle_at_mission_epoch_deg);
    end
end

function sys = apply_pre_berthing_drag_scope(sys, run_cfg)
    if drag_starts_after_berthing(run_cfg) && orbital_drag_enabled(sys)
        sys.environment.atmospheric_drag.enabled = false;
        fprintf('Environment scope: orbital atmospheric drag held OFF through Phase 1/2; enabled after berthing.\n');
    end
end

function warn_if_mission_json_environment_mismatch(cfg, sys)
    if isempty(fieldnames(cfg)) || ~has_json_path(cfg, {'environment','atmospheric_drag'})
        return;
    end

    json_drag_enabled = get_json_bool(cfg, {'environment','atmospheric_drag','enabled'}, false);
    json_drag_model = upper(get_json_string(cfg, {'environment','atmospheric_drag','model'}, "ISA76"));
    sys_drag = sys.environment.atmospheric_drag;
    sys_drag_enabled = parse_bool_setting(sys_drag.enabled);
    sys_drag_model = upper(string(sys_drag.model));

    if json_drag_enabled ~= sys_drag_enabled || json_drag_model ~= sys_drag_model
        fprintf(['WARNING: selected mission JSON atmospheric-drag setting (%s/%s) does not match ' ...
                 'current MATLAB setting (%s/%s). Regenerate or pin a matching Python Phase 1 JSON for consistent drag-on runs.\n'], ...
                bool_label(json_drag_enabled), char(json_drag_model), ...
                bool_label(sys_drag_enabled), char(sys_drag_model));
    end
end

function [phasing_mode, custom_params] = apply_json_to_phase1(phasing_mode, custom_params, cfg)
    if isempty(fieldnames(cfg)) || ~isfield(cfg, 'phase1')
        return;
    end

    phasing_mode = get_json_string(cfg, {'phase1','mode'}, phasing_mode);
    custom_params.burn_model = get_json_string(cfg, {'phase1','burn_model'}, custom_params.burn_model);

    if has_json_path(cfg, {'phase1','phase_angle_deg'})
        custom_params.phase_angle = get_json_number(cfg, {'phase1','phase_angle_deg'}, custom_params.phase_angle);
        custom_params.phase_angle_unit = "deg";
    elseif has_json_path(cfg, {'phase1','phase_angle_rad'})
        custom_params.phase_angle = get_json_number(cfg, {'phase1','phase_angle_rad'}, custom_params.phase_angle);
        custom_params.phase_angle_unit = "rad";
    end

    if has_json_path(cfg, {'phase1','gamma_deg'})
        custom_params.gamma = get_json_number(cfg, {'phase1','gamma_deg'}, custom_params.gamma);
        custom_params.gamma_unit = "deg";
    elseif has_json_path(cfg, {'phase1','gamma_rad'})
        custom_params.gamma = get_json_number(cfg, {'phase1','gamma_rad'}, custom_params.gamma);
        custom_params.gamma_unit = "rad";
    end

    custom_params.delta_v = get_json_number(cfg, {'phase1','delta_v_m_s'}, custom_params.delta_v);
    custom_params.desired_rel_lvlh = get_json_vector(cfg, {'phase1','desired_rel_lvlh_m'}, custom_params.desired_rel_lvlh);

    custom_params.finite_burn_thrust = get_json_number(cfg, {'maneuver','finite_burn_thrust_N'}, custom_params.finite_burn_thrust);
    custom_params.finite_burn_isp = get_json_number(cfg, {'maneuver','finite_burn_isp_s'}, custom_params.finite_burn_isp);
    custom_params.dt_burn = get_json_number(cfg, {'maneuver','finite_burn_dt_s'}, custom_params.dt_burn);
    custom_params.max_single_burn_duration = get_json_number(cfg, {'maneuver','max_single_burn_duration_s'}, custom_params.max_single_burn_duration);
    custom_params.max_single_burn_delta_v = get_json_number(cfg, {'maneuver','max_single_burn_delta_v_m_s'}, custom_params.max_single_burn_delta_v);

    custom_params.time_step = get_json_number(cfg, {'phase1','time_step_s'}, custom_params.time_step);
    custom_params.dt_phase = get_json_number(cfg, {'phase1','dt_phase_s'}, custom_params.dt_phase);
    custom_params.dt_capture = get_json_number(cfg, {'phase1','dt_capture_s'}, custom_params.dt_capture);
    custom_params.max_wait = get_json_number(cfg, {'phase1','max_wait_s'}, custom_params.max_wait);
    custom_params.max_capture_time = get_json_number(cfg, {'phase1','max_capture_time_s'}, custom_params.max_capture_time);
    custom_params.phase_tol = get_json_number(cfg, {'phase1','phase_tol_rad'}, custom_params.phase_tol);
    custom_params.event_time_tol = get_json_number(cfg, {'phase1','event_time_tol_s'}, custom_params.event_time_tol);
    custom_params.capture_pos_tol = get_json_number(cfg, {'phase1','capture_pos_tol_m'}, custom_params.capture_pos_tol);
    custom_params.min_capture_time = get_json_number(cfg, {'phase1','min_capture_time_s'}, custom_params.min_capture_time);
end

