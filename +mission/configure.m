    sys.maneuver.max_single_burn_delta_v = get_run_number_field(run_cfg, {'maneuver','max_single_burn_delta_v_m_s'}, sys.maneuver.max_single_burn_delta_v);

    sys.reentry_vehicle.vehicle_mode = get_run_string_field(run_cfg, {'reentry','vehicle_mode'}, sys.reentry_vehicle.vehicle_mode);
    sys.reentry_vehicle.selected_shape = get_run_string_field(run_cfg, {'reentry','shape'}, sys.reentry_vehicle.selected_shape);
    sys.reentry_vehicle.dt = get_run_number_field(run_cfg, {'reentry','dt_s'}, sys.reentry_vehicle.dt);
    sys.reentry_vehicle.max_time = get_run_number_field(run_cfg, {'reentry','max_time_s'}, sys.reentry_vehicle.max_time);
    sys.reentry_vehicle.terminal_altitude = get_run_number_field(run_cfg, {'reentry','terminal_altitude_m'}, sys.reentry_vehicle.terminal_altitude);
    sys.reentry_vehicle.lift_enabled = get_run_bool_field(run_cfg, {'reentry','lift_enabled'}, sys.reentry_vehicle.lift_enabled);
    sys.reentry_vehicle.gravity_model = get_run_string_field(run_cfg, {'reentry','gravity_model'}, sys.reentry_vehicle.gravity_model);
    if has_run_path(run_cfg, {'reentry','aoa_deg'}) && ~isempty(get_run_value(run_cfg, {'reentry','aoa_deg'}, []))
        sys.reentry_vehicle.aoa_deg = get_run_number_field(run_cfg, {'reentry','aoa_deg'}, 20);
    end
    sys.reentry_vehicle.bank_angle_deg = get_run_number_field(run_cfg, {'reentry','bank_angle_deg'}, sys.reentry_vehicle.bank_angle_deg);
    sys.reentry_vehicle.los_margin_altitude = get_run_number_field(run_cfg, {'reentry','los_margin_altitude_m'}, sys.reentry_vehicle.los_margin_altitude);
    sys.reentry_vehicle.capsule.mass_kg = get_run_number_field(run_cfg, {'reentry','capsule','mass_kg'}, sys.reentry_vehicle.capsule.mass_kg);
    sys.reentry_vehicle.capsule.add_to_chaser_initial_mass = get_run_bool_field(run_cfg, {'reentry','capsule','add_to_chaser_initial_mass'}, sys.reentry_vehicle.capsule.add_to_chaser_initial_mass);
    sys.reentry_vehicle.capsule.separation_mode = get_run_string_field(run_cfg, {'reentry','capsule','separation_mode'}, sys.reentry_vehicle.capsule.separation_mode);
    sys.reentry_vehicle.capsule.use_paper_entry_conditions = get_run_bool_field(run_cfg, {'reentry','capsule','use_paper_entry_conditions'}, sys.reentry_vehicle.capsule.use_paper_entry_conditions);
    sys.reentry_vehicle.capsule.altitude_termination_enabled = get_run_bool_field(run_cfg, {'reentry','capsule','altitude_termination_enabled'}, sys.reentry_vehicle.capsule.altitude_termination_enabled);
    sys.reentry_vehicle.spaceplane.communication.enabled = get_run_bool_field(run_cfg, {'reentry','communication','enabled'}, sys.reentry_vehicle.spaceplane.communication.enabled);
    sys.reentry_vehicle.spaceplane.communication.relay_mode = get_run_string_field(run_cfg, {'reentry','communication','relay_mode'}, sys.reentry_vehicle.spaceplane.communication.relay_mode);
    sys.reentry_vehicle.spaceplane.communication.antenna_mount = get_run_string_field(run_cfg, {'reentry','communication','antenna_mount'}, sys.reentry_vehicle.spaceplane.communication.antenna_mount);
    sys.reentry_vehicle.spaceplane.communication.beam_half_angle_deg = get_run_number_field(run_cfg, {'reentry','communication','beam_half_angle_deg'}, sys.reentry_vehicle.spaceplane.communication.beam_half_angle_deg);
    sys.reentry_vehicle.spaceplane.communication.min_range_m = get_run_number_field(run_cfg, {'reentry','communication','min_range_m'}, sys.reentry_vehicle.spaceplane.communication.min_range_m);
    sys.reentry_vehicle.spaceplane.communication.max_range_m = get_run_number_field(run_cfg, {'reentry','communication','max_range_m'}, sys.reentry_vehicle.spaceplane.communication.max_range_m);
    sys.reentry_vehicle.spaceplane.communication.tracking_scope = get_run_string_field(run_cfg, {'reentry','communication','tracking_scope'}, sys.reentry_vehicle.spaceplane.communication.tracking_scope);
    sys.reentry_vehicle.spaceplane.communication.evaluate_bank_feasibility = get_run_bool_field(run_cfg, {'reentry','communication','evaluate_bank_feasibility'}, sys.reentry_vehicle.spaceplane.communication.evaluate_bank_feasibility);
    sys.reentry_vehicle.spaceplane.communication.earth_fixed_to_eci_angle_at_mission_epoch_deg = ...
        get_run_number_field(run_cfg, ...
            {'reentry','communication','earth_fixed_to_eci_angle_at_mission_epoch_deg'}, ...
            sys.reentry_vehicle.spaceplane.communication.earth_fixed_to_eci_angle_at_mission_epoch_deg);
    sys.reentry_vehicle.uncertainty.density_scale = get_run_number_field(run_cfg, {'reentry','uncertainty','density_scale'}, sys.reentry_vehicle.uncertainty.density_scale);
    sys.reentry_vehicle.uncertainty.cd_scale = get_run_number_field(run_cfg, {'reentry','uncertainty','cd_scale'}, sys.reentry_vehicle.uncertainty.cd_scale);
    sys.reentry_vehicle.uncertainty.ld_scale = get_run_number_field(run_cfg, {'reentry','uncertainty','ld_scale'}, sys.reentry_vehicle.uncertainty.ld_scale);
    if sys.reentry_vehicle.capsule.use_paper_entry_conditions
        error('mission:PrescribedIntegratedEntry','Paper entry conditions belong to standalone studies. Set explicit deorbit targets instead.');
    end

    if has_run_path(run_cfg, {'environment','atmospheric_drag'})
        drag = run_cfg.environment.atmospheric_drag;
        sys.environment.atmospheric_drag.enabled = get_run_bool_field(run_cfg, {'environment','atmospheric_drag','enabled'}, sys.environment.atmospheric_drag.enabled);
        sys.environment.atmospheric_drag.model = get_run_string_field(run_cfg, {'environment','atmospheric_drag','model'}, sys.environment.atmospheric_drag.model);
        sys.environment.atmospheric_drag.use_matlab_atmosisa = get_run_bool_field(run_cfg, {'environment','atmospheric_drag','use_matlab_atmosisa'}, sys.environment.atmospheric_drag.use_matlab_atmosisa);
        sys.environment.atmospheric_drag.co_rotate_atmosphere = get_run_bool_field(run_cfg, {'environment','atmospheric_drag','co_rotate_atmosphere'}, sys.environment.atmospheric_drag.co_rotate_atmosphere);
        if isfield(drag, 'earth_rotation_rad_s')
            sys.environment.atmospheric_drag.earth_rotation_rad_s = get_run_number_field(run_cfg, {'environment','atmospheric_drag','earth_rotation_rad_s'}, sys.environment.atmospheric_drag.earth_rotation_rad_s);
        end
    end
end

function sys = refresh_derived_sys(sys)
    r_insert = sys.Re + sys.h_insert;
    r_target = sys.Re + sys.h_target;
    a_transfer = 0.5 * (r_insert + r_target);
    sys.phase = pi * (1 - (a_transfer / r_target)^1.5);
end

function [phasing_mode, custom_params] = apply_run_config_to_phase1(phasing_mode, custom_params, run_cfg)
    custom_params.hohmann_method=run_cfg.phase1.hohmann_method;
    custom_params.nominal=run_cfg.phase1.nominal;
    custom_params.correction=run_cfg.phase1.correction;
    phasing_mode = get_run_string_field(run_cfg, {'phase1','mode'}, phasing_mode);
    custom_params.burn_model = get_run_string_field(run_cfg, {'maneuver','burn_model'}, custom_params.burn_model);
    custom_params.finite_burn_thrust = get_run_number_field(run_cfg, {'maneuver','finite_burn_thrust_N'}, custom_params.finite_burn_thrust);
    custom_params.finite_burn_isp = get_run_number_field(run_cfg, {'maneuver','finite_burn_isp_s'}, custom_params.finite_burn_isp);
    custom_params.dt_burn = get_run_number_field(run_cfg, {'maneuver','finite_burn_dt_s'}, custom_params.dt_burn);
    custom_params.max_single_burn_duration = get_run_number_field(run_cfg, {'maneuver','max_single_burn_duration_s'}, custom_params.max_single_burn_duration);
    custom_params.max_single_burn_delta_v = get_run_number_field(run_cfg, {'maneuver','max_single_burn_delta_v_m_s'}, custom_params.max_single_burn_delta_v);
    custom_params.use_thrust_noise = get_run_bool_field(run_cfg, {'maneuver','use_thrust_noise'}, custom_params.use_thrust_noise);
    custom_params.multi_hohmann_legs = get_run_value(run_cfg, {'maneuver','multi_hohmann_legs'}, custom_params.multi_hohmann_legs);

    if has_nonempty_run_value(run_cfg, {'phase1','phase_angle_deg'})
        custom_params.phase_angle = get_run_number_field(run_cfg, {'phase1','phase_angle_deg'}, rad2deg(custom_params.phase_angle));
        custom_params.phase_angle_unit = "deg";
    elseif has_nonempty_run_value(run_cfg, {'phase1','phase_angle_rad'})
        custom_params.phase_angle = get_run_number_field(run_cfg, {'phase1','phase_angle_rad'}, custom_params.phase_angle);
        custom_params.phase_angle_unit = "rad";
    end

    custom_params.delta_v = get_run_number_field(run_cfg, {'phase1','delta_v_m_s'}, custom_params.delta_v);
    if has_nonempty_run_value(run_cfg, {'phase1','gamma_deg'})
        custom_params.gamma = get_run_number_field(run_cfg, {'phase1','gamma_deg'}, rad2deg(custom_params.gamma));
        custom_params.gamma_unit = "deg";
    elseif has_nonempty_run_value(run_cfg, {'phase1','gamma_rad'})
        custom_params.gamma = get_run_number_field(run_cfg, {'phase1','gamma_rad'}, custom_params.gamma);
        custom_params.gamma_unit = "rad";
    end

    custom_params.desired_rel_lvlh = get_run_vector_field(run_cfg, {'phase1','desired_rel_lvlh_m'}, custom_params.desired_rel_lvlh);
    custom_params.time_step = get_run_number_field(run_cfg, {'phase1','time_step_s'}, custom_params.time_step);
    custom_params.dt_phase = get_run_number_field(run_cfg, {'phase1','dt_phase_s'}, custom_params.dt_phase);
    custom_params.dt_capture = get_run_number_field(run_cfg, {'phase1','dt_capture_s'}, custom_params.dt_capture);
    custom_params.max_wait = get_run_number_field(run_cfg, {'phase1','max_wait_s'}, custom_params.max_wait);
    custom_params.max_capture_time = get_run_number_field(run_cfg, {'phase1','max_capture_time_s'}, custom_params.max_capture_time);
    custom_params.phase_tol = get_run_number_field(run_cfg, {'phase1','phase_tol_rad'}, custom_params.phase_tol);
    custom_params.event_time_tol = get_run_number_field(run_cfg, {'phase1','event_time_tol_s'}, custom_params.event_time_tol);
    custom_params.capture_pos_tol = get_run_number_field(run_cfg, {'phase1','capture_pos_tol_m'}, custom_params.capture_pos_tol);
    custom_params.min_capture_time = get_run_number_field(run_cfg, {'phase1','min_capture_time_s'}, custom_params.min_capture_time);
end

function [phasing_mode, custom_params] = apply_phase1_env_overrides(phasing_mode, custom_params, run_cfg)
    if ~get_run_bool_field(run_cfg, {'runtime','allow_environment_overrides'}, true)
        return;
    end

    burn_model_env = strtrim(string(getenv('RENDEZVOUS_BURN_MODEL')));
    if strlength(burn_model_env) > 0
        custom_params.burn_model = upper(burn_model_env);
    end
end

